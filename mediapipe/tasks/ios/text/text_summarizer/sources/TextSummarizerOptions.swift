/// Summary style generated by `TextSummarizer`.
public enum TextSummarizerMode: Int, Sendable, Equatable, Hashable, CaseIterable {
  /// Generates a concise paragraph summary.
  case tldr = 0

  /// Generates bulleted key points.
  case keyPoints = 1

  /// Underlying C mode representation.
  package var cMode: MpTextSummarizerMode {
    switch self {
    case .tldr:
      return MP_TEXT_SUMMARIZER_MODE_TLDR
    case .keyPoints:
      return MP_TEXT_SUMMARIZER_MODE_KEYPOINTS
    }
  }
}

/// Configuration options for setting up a `TextSummarizer` task.
public struct TextSummarizerOptions: Sendable, Equatable, Hashable {
  /// LiteRT-LM `ERROR` log severity, matching the C++ `TextSummarizerOptions` default.
  private static let defaultMinLogSeverity: Int32 = 4

  /// Base options for model loading and hardware delegation. Only `.cpu` is supported.
  public var baseOptions: BaseOptions

  /// Output summarization format.
  public var mode: TextSummarizerMode

  /// Maximum combined input and output token budget, or `0` to use the model's default capacity.
  public var maxNumTokens: Int

  /// Directory used for weight and program caching, or `":nocache"` to disable caching.
  public var cacheDirectory: String?

  /// Creates options with default `.keyPoints` mode and CPU execution.
  public init(
    baseOptions: BaseOptions = BaseOptions(),
    mode: TextSummarizerMode = .keyPoints,
    maxNumTokens: Int = 0,
    cacheDirectory: String? = nil
  ) {
    self.baseOptions = baseOptions
    self.mode = mode
    self.maxNumTokens = maxNumTokens
    self.cacheDirectory = cacheDirectory
  }

  /// Validates configuration and invokes `body` with a C `MpTextSummarizerOptions` struct whose
  /// pointer fields remain valid for the duration of the closure call.
  package func withCOptions<Result>(
    _ body: (MpTextSummarizerOptions) throws -> Result
  ) throws -> Result {
    guard baseOptions.delegate == .cpu else {
      throw TasksError.invalidArgument("TextSummarizer only supports the CPU delegate.")
    }
    guard maxNumTokens >= 0, let cMaxTokens = Int32(exactly: maxNumTokens) else {
      throw TasksError.invalidArgument(
        "maxNumTokens must be between 0 and \(Int32.max), got \(maxNumTokens).")
    }
    return try baseOptions.withCOptions { cBaseOptions in
      try cacheDirectory.withCString { cacheDirPtr in
        var cOptions = MpTextSummarizerOptions()
        cOptions.base_options = cBaseOptions
        cOptions.mode = mode.cMode
        cOptions.max_num_tokens = cMaxTokens
        cOptions.cache_dir = cacheDirPtr.map { UnsafeMutablePointer(mutating: $0) }
        cOptions.min_log_severity = Self.defaultMinLogSeverity
        return try body(cOptions)
      }
    }
  }
}
