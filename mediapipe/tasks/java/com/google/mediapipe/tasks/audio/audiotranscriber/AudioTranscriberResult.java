package com.google.mediapipe.tasks.audio.audiotranscriber;

import androidx.annotation.Keep;
import com.google.auto.value.AutoValue;
import com.google.mediapipe.tasks.core.TaskResult;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;

/** Represents the transcription results generated by {@link AudioTranscriber}. */
@AutoValue
@Keep
@SuppressWarnings({
  "AutoValueImmutableFields", // 3P API that does not depend on Guava
  "GoodTime", // 3P API uses primitive timestamps
})
public abstract class AudioTranscriberResult implements TaskResult {

  /** Represents a single transcribed segment emitted by {@link AudioTranscriber}. */
  @AutoValue
  @Keep
  public abstract static class Segment {
    /** The transcribed text of this segment. */
    public abstract String transcript();

    /** Whether this segment is final or an interim hypothesis. */
    public abstract boolean isFinal();

    /** Start timestamp of the segment in milliseconds. */
    public abstract long fromTimestampMs();

    /** End timestamp of the segment in milliseconds. */
    public abstract long toTimestampMs();

    /** Creates a {@link Segment} instance. */
    @Keep
    public static Segment create(
        String transcript, boolean isFinal, long fromTimestampMs, long toTimestampMs) {
      return new AutoValue_AudioTranscriberResult_Segment(
          transcript, isFinal, fromTimestampMs, toTimestampMs);
    }
  }

  /** Returns the list of transcribed segments. */
  public abstract List<Segment> segments();

  @Override
  public abstract long timestampMs();

  /** Creates an {@link AudioTranscriberResult} instance. */
  @Keep
  public static AudioTranscriberResult create(List<Segment> segments, long timestampMs) {
    return new AutoValue_AudioTranscriberResult(
        Collections.unmodifiableList(new ArrayList<>(segments)), timestampMs);
  }

  /** Returns the combined transcript text joining all non-empty segments with a single space. */
  public String getText() {
    StringBuilder builder = new StringBuilder();
    for (Segment segment : segments()) {
      String transcript = segment.transcript();
      if (transcript.isEmpty()) {
        continue;
      }
      if (builder.length() > 0
          && !Character.isWhitespace(builder.charAt(builder.length() - 1))
          && !Character.isWhitespace(transcript.charAt(0))) {
        builder.append(' ');
      }
      builder.append(transcript);
    }
    return builder.toString();
  }
}
